/*
 * Karateka (IBM version) font, converted from the asm sources.
 *
 *   D_B6FA  -> font_offset[] + font_data[]   (glyph bitmaps, 1 bpp)
 *   D_D9E6  -> font_height[]
 *   D_DA04  -> font_width_bytes[]
 *   D_DA22  -> font_advance_px[]
 *
 * Glyph index = character - 'a'.  The 30 glyphs cover 'a'..'z' plus
 * '{' '|' '}' '~', which the game text uses as:
 *     '{' = '.'   '|' = ','   '}' = ':'   '~' = '-'
 *
 * Glyph layout (see k_puts in the asm):
 *   - column-major: for each of width_bytes columns, height bytes top->bottom
 *   - each byte is 8 horizontal pixels, MSB = leftmost pixel
 *   - glyph size is width_bytes * height, but glyphs are not packed tightly,
 *     so always locate a glyph through font_offset[], never by summing sizes
 *
 * font_offset[] values are copied unchanged from the asm, i.e. they are
 * relative to the start of D_B6FA, which includes the 40-word offset table
 * itself (80 bytes = 0x50).  To index font_data[], subtract FONT_TABLE_BYTES.
 * Entries 30..39 are unused and point at/after the end of the glyph data.
 */

/* Map a game-text character to a glyph index, or -1 if it has no glyph
 * (the asm just advances the cursor 2 bytes for anything below 'a'). */
static inline int font_index(char c)
{
    return (c >= 'a' && c <= '~') ? (c - 'a') : -1;
}

/* Pointer to the first byte of glyph i (column-major, height bytes/column). */
static inline const uint8_t *font_glyph(int i)
{
    return &font_data[font_offset[i] - FONT_TABLE_BYTES];
}

